"""Build a subfolder-only upload and a new Cloudflare Pages preview upload.

Run after npm run build. Archives contain only browser assets, never source briefs,
internal cost calculations, credentials or the existing site's root index.html.
"""
from pathlib import Path
from datetime import datetime
import argparse, re, shutil, zipfile

parser=argparse.ArgumentParser()
parser.add_argument('--production',action='store_true',help='A szerző által kért, éles domainre szánt változat.')
PRODUCTION=parser.parse_args().production

ROOT=Path(__file__).resolve().parents[1]
DIST=ROOT/'dist'
DEPLOY=ROOT/'deploy'
PREFIX='/eletutak-talalkozasa/'
PAGE_PATHS=[Path('eletutak-talalkozasa')/lang/'index.html' for lang in ['', 'en', 'de', 'it']]
LEGAL_PATHS=[Path('eletutak-talalkozasa')/name for name in ['adatkezeles/index.html','impresszum/index.html','legal.css']]
for p in PAGE_PATHS+LEGAL_PATHS:
    if not (DIST/p).is_file(): raise SystemExit('Előbb futtasd: npm run build')

def clean_generated(path):
    marker=path/'.generated-landing'
    if path.exists():
        if not marker.is_file(): raise SystemExit(f'Nem írok felül ismeretlen mappát: {path}')
        shutil.rmtree(path)
    path.mkdir(parents=True)
    marker.write_text('Generated by scripts/package_landing.py\n')

def rebase(text):
    text=text.replace('/assets/',PREFIX+'assets/').replace('src="/config.js"',f'src="{PREFIX}config.js"')
    # Social-image URLs already include the landing prefix; rebase root images only.
    text=re.sub(r'(?<!/eletutak-talalkozasa)/images/eletutak/',PREFIX+'images/eletutak/',text)
    return re.sub(r'''(?<=["'(])/forest-canopy\.webp''',PREFIX+'forest-canopy.webp',text)

def release_html(text,path):
    if not PRODUCTION:return text
    if path==PAGE_PATHS[0]:
        text=text.replace('<meta name="robots" content="noindex,nofollow">','<meta name="robots" content="index,follow">')
    if path in PAGE_PATHS:
        # A régi fődomain jelenleg 404-et ad; az önálló landing nem küld oda látogatót.
        text=re.sub(r'<div class="lp-hero-top"><a href="/">.*?</a><span aria-hidden="true">/</span>', '<div class="lp-hero-top">',text,count=1)
        text=re.sub(r'<a class="lp-back" href="/">.*?</a>','',text,count=1)
        text=text.replace('class="lp-brand" href="/"','class="lp-brand" href="#lp-content"')
        text=re.sub(r'aria-label="Sarkadi Sándor — [^"]*"','aria-label="Sarkadi Sándor"',text)
        text=re.sub(r'<p class="lp-demo-note">.*?</p>','',text,count=1,flags=re.S)
    if path in LEGAL_PATHS and path.suffix=='.html':
        effective='2026. november 10.' if 'adatkezeles' in path.parts else '2026. november 9.'
        text=re.sub(r'<p class="draft">.*?</p>',f'<p>Hatályos: {effective}</p>',text,count=1,flags=re.S)
    return text

# Follow only the new landing's asset graph. Do not distribute the old home bundle.
needed=set()
queue=[]
for p in PAGE_PATHS:
    queue += re.findall(r'(?:src|href)="/assets/([^"?#]+)"',(DIST/p).read_text())
while queue:
    name=queue.pop()
    if name in needed: continue
    path=DIST/'assets'/name
    if not path.is_file(): raise SystemExit(f'Hiányzó build-állomány: {name}')
    needed.add(name)
    if path.suffix in {'.js','.css'}:
        text=path.read_text()
        queue += re.findall(r'/assets/([^\s"\'`)?#]+)',text)
        queue += [ref for ref in re.findall(r'["\'`]\./([^"\'`?#]+)["\'`]',text) if (DIST/'assets'/ref).is_file()]

base=DEPLOY/('eles-statikus-tarhely' if PRODUCTION else 'statikus-tarhely')
clean_generated(base)
sub=base/'eletutak-talalkozasa'
(sub/'assets').mkdir(parents=True)
for p in PAGE_PATHS:
    dest=base/p;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_text(release_html(rebase((DIST/p).read_text()),p))
for p in LEGAL_PATHS:
    dest=base/p;dest.parent.mkdir(parents=True,exist_ok=True)
    if p.suffix=='.html':dest.write_text(release_html((DIST/p).read_text(),p))
    else:shutil.copyfile(DIST/p,dest)
for name in sorted(needed):
    src=DIST/'assets'/name;dest=sub/'assets'/name
    if src.suffix in {'.js','.css'}: dest.write_text(rebase(src.read_text()))
    else: shutil.copyfile(src,dest)
for name in ['config.js','forest-canopy.webp']:
    shutil.copyfile(DIST/name,sub/name)
if PRODUCTION:
    config_path=sub/'config.js'
    config_text=config_path.read_text()
    if config_text.count('formEnabled: false')!=1:raise SystemExit('A forráskonfiguráció kapcsolója külön ellenőrzést igényel.')
    config_text=config_text.replace('formEnabled: false, // Csak a fogadás és a végleges tájékoztató ellenőrzése után.','formEnabled: true, // Éles változat: előre kitöltött Google-űrlap, ott véglegesített beküldés.')
    if config_text.count('metaPixelEnabled: false')!=1:raise SystemExit('A Meta Pixel éles kapcsolója külön ellenőrzést igényel.')
    config_text=config_text.replace('metaPixelEnabled: false','metaPixelEnabled: true')
    config_path.write_text(config_text)
photo_refs=set()
for p in PAGE_PATHS:
    photo_refs.update(re.findall(r'src="/(images/eletutak/[^"?#]+\.webp)"',(DIST/p).read_text()))
for name in sorted(photo_refs):
    source=DIST/name
    if not source.is_file():raise SystemExit(f'Hiányzó programkép: {name}')
    dest=sub/name;dest.parent.mkdir(parents=True,exist_ok=True)
    shutil.copyfile(source,dest)
shutil.copytree(DIST/'font-licenses',sub/'font-licenses')

preview=DEPLOY/('eles-cloudflare' if PRODUCTION else 'cloudflare-uj-projekt')
clean_generated(preview)
shutil.copytree(sub,preview/'eletutak-talalkozasa')
for p in (preview/'eletutak-talalkozasa').rglob('index.html'):
    p.write_text(p.read_text().replace('href="/"','href="https://sarkadisandor.hu/"'))
(preview/'index.html').write_text('''<!doctype html><html lang="hu"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex,nofollow"><meta http-equiv="refresh" content="0;url=/eletutak-talalkozasa/"><title>Életutak találkozása</title></head><body><a href="/eletutak-talalkozasa/">Életutak találkozása — megnyitás</a></body></html>''')
(preview/'_redirects').write_text('/ /eletutak-talalkozasa/ 302\n')
(preview/'_headers').write_text('/eletutak-talalkozasa/config.js\n  Cache-Control: no-store, max-age=0\n\n/eletutak-talalkozasa/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: strict-origin-when-cross-origin\n')

def archive(source,name):
    output=DEPLOY/name
    with zipfile.ZipFile(output,'w',zipfile.ZIP_DEFLATED) as z:
        for p in sorted(source.rglob('*')):
            if not p.is_file() or p.name=='.generated-landing':continue
            info=zipfile.ZipInfo(str(p.relative_to(source)),datetime.now().timetuple()[:6])
            info.external_attr=(0o100644<<16);info.compress_type=zipfile.ZIP_DEFLATED
            z.writestr(info,p.read_bytes())
    with zipfile.ZipFile(output) as z:
        assert z.testzip() is None
        assert not any(n.startswith(('agy/','src/','tests/')) or n.endswith('.env') for n in z.namelist())
        assert all(str(p) in z.namelist() for p in PAGE_PATHS+LEGAL_PATHS)
        for p in PAGE_PATHS:
            html=z.read(str(p)).decode()
            image=re.search(r'<meta property="og:image" content="https://sarkadisandor.hu([^"]+)"',html)
            assert image and image.group(1).lstrip('/') in z.namelist(),(p,'Missing social image')
        if source==base:assert 'index.html' not in z.namelist()
        else:assert 'index.html' in z.namelist() and '_redirects' in z.namelist()
    print(output.relative_to(ROOT),output.stat().st_size,'bájt')
archive(base,'Eletutak-sarkadisandor-hu.zip' if PRODUCTION else 'Eletutak-statikus-aloldal.zip')
archive(preview,'Eletutak-Cloudflare-eles.zip' if PRODUCTION else 'Eletutak-Cloudflare-uj-projekt.zip')
# Check every same-site browser resource in the nested deployment.
for folder in [base,preview]:
    for p in (folder/'eletutak-talalkozasa').rglob('*'):
        if not p.is_file() or p.suffix not in {'.html','.css','.js'}:continue
        text=p.read_text()
        assert not re.search(r'(?:src|href)="/(?:assets/|images/eletutak/|config.js)',text),p
        assert not re.search(r'url\(["\']?/assets/',text),p
        for ref in re.findall(r'(?:src|href)="('+PREFIX+r'(?:assets/[^"?#]+|images/eletutak/[^"?#]+|config.js))"',text):
            assert (folder/ref.lstrip('/')).is_file(),(p,ref)
print(f'Önálló aloldalcsomag elkészült; {len(needed)} szükséges böngésző-asset és {len(photo_refs)} kép, főoldalkód nélkül.')
