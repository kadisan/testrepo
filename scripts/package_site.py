"""Package the tested full site for a separate, versioned Static Assets Worker.

Never changes the existing landing-only Pages project. Legal and foreign pages
stay on the previous published deployment through the domain router.
"""
import json
import re
import shutil
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]
dist = root / 'dist'
target = root / 'deploy' / 'sarkadi-site'
marker = target / '.generated-site'
if not all((dist / f).is_file() for f in ['index.html', 'tai-chi/index.html', 'eletutak-talalkozasa/index.html', 'config.js']):
    raise SystemExit('Előbb futtasd: npm run build')
if target.exists():
    if not marker.is_file():
        raise SystemExit('Ismeretlen csomagolási mappát nem írok felül.')
    shutil.rmtree(target)
shutil.copytree(dist, target)
marker.write_text('Generated by scripts/package_site.py\n')
config = (target / 'config.js').read_text()
# The existing Google handoff requires final submission on Google. It is never
# reported as a confirmed Lead by the main/Tai Chi application.
config = re.sub(r'formEnabled:\s*false', 'formEnabled: true', config)
config = re.sub(r'metaPixelEnabled:\s*false', 'metaPixelEnabled: true', config)
(target / 'config.js').write_text(config)
landing = target / 'eletutak-talalkozasa/index.html'
html = landing.read_text().replace('<meta name="robots" content="noindex,nofollow">', '<meta name="robots" content="index,follow">')
landing.write_text(html)
# No inherited preview-wide Disallow/noindex rule may enter the live build.
(target / 'robots.txt').write_text('User-agent: *\nAllow: /\nSitemap: https://sarkadisandor.hu/sitemap.xml\n')
(target / 'sitemap.xml').write_text('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'+''.join('<url><loc>https://sarkadisandor.hu'+p+'</loc></url>' for p in ['/', '/tai-chi/', '/eletutak-talalkozasa/'])+'</urlset>\n')
(target / '_headers').write_text('/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: strict-origin-when-cross-origin\n\n/config.js\n  Cache-Control: no-store, max-age=0\n')
commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root, text=True).strip()
(target / 'release-version.json').write_text(json.dumps({'sourceBranch':'site/csendes-konyv','sourceCommit':commit,'release':'fooldal-elobb-eletutak-utana','googleFormHandoffEnabled':True,'callbackReceiverVerified':True}, ensure_ascii=False, indent=2)+'\n')
print(f'Élesítésre előkészített webes csomag: {target}')
